export function buildDebtors(config: ScoreConfig = DEFAULT_SCORE_CONFIG): Debtor[] {
  return INITIAL_DEBTORS_RAW.map((raw) => {
    const totalDebt = raw.debts.reduce((sum, d) => sum + d.amount, 0);
    // distinct creditors count
    const creditorSet = new Set(raw.debts.map((d) => d.creditorName.toLowerCase().trim()));
    const creditorCount = creditorSet.size;
    const { score, level } = calculateRiskScore(totalDebt, creditorCount, config);

    return {
      ...raw,
      totalDebt,
      creditorCount,
      riskScore: score,
      riskLevel: level,
    };
  });
}

